"""Methodology, interpretation and limitations."""
import streamlit as st

from app.views.common import banner, footer
from src.data.loader import PROJECT_ROOT
from src.models.bayesian_network import edge_table


def _img(rel, caption):
    p = PROJECT_ROOT / rel
    if p.exists():
        st.image(str(p), caption=caption)
    else:
        st.info(f"Figure not found: {rel}")


def render() -> None:
    st.title("Methods, interpretation and limitations")
    banner()
    t1, t2, t3, t4, t5, t6 = st.tabs([
        "Phase 2 Deep Learning & Stacking",
        "Phase 2 Validation Protocols & HPO",
        "Interpretation & SHAP Non-linearities",
        "Pipeline and classical models",
        "Bayesian network",
        "Limitations and ethics",
    ])

    with t1:
        st.subheader("Phase 2: Multi-Cohort Deep Learning & Bayesian-Neural Integration")
        st.markdown(
            r"#### Tabular Multilayer Perceptron (MLP)" "\n"
            r"- **Architecture:** Feedforward neural network implemented in PyTorch with configurable layout (`16`, `16-8`, or `32-16` hidden units) and ReLU activations." "\n"
            r"- **Regularisation Triad:** Dropout (p=0.1 to 0.5), Adam optimiser with L2 weight decay ($10^{-4}$ to $10^{-2}$), and training-only early stopping with patience (15 epochs) on inner validation log loss." "\n"
            r"- **Preprocessing:** Continuous variables standardized via `StandardScaler`, nominal variables one-hot encoded, missing values imputed with median/mode strictly inside training splits." "\n\n"
            r"#### Bayesian-Neural Stacking Classifier (`BNMLPStackingClassifier`)" "\n"
            r"- **Cross-Fitting:** Inside each training fold, internal 3-fold cross-validation generates out-of-fold probability predictions for both the Bayesian network and the MLP." "\n"
            r"- **Meta-Combiner:** A regularised logistic regression model combines the two probability predictions into a final integrated risk prediction." "\n"
            r"- **Leakage Prevention:** The meta-combiner is never trained on probabilities generated by base estimators that saw those patients during fitting." "\n\n"
            r"#### Hyperparameter Optimisation (`OptunaSearchCV`)" "\n"
            r"- **Tree-structured Parzen Estimator (TPE):** Sequential model-based search models $p(x|y)$ via two kernel density estimators ($\ell(x)$ and $g(x)$) to minimize inner-fold log loss." "\n"
            r"- **Library Delegation:** Candidate sampling, trial pruning, and inner cross-validation are owned entirely by the Optuna integration library."
        )

    with t2:
        st.subheader("Phase 2 Validation Protocols & Cross-Cohort Evaluation")
        st.markdown(
            "#### Protocol 1: Pooled Multi-Cohort Nested Cross-Validation\n"
            "- **Design:** 5-fold cross-validation repeated 5 times (25 outer folds) across all 920 patients from all four centres.\n"
            "- **Strict Hierarchy:** Data preprocessing, imputation, and Optuna TPE hyperparameter tuning occur entirely within inner folds to prevent data leakage.\n"
            "- **Statistical Inference:** Out-of-fold pooled performance accompanied by 2,000-sample patient-level bootstrap 95% confidence intervals.\n\n"
            "#### Protocol 2: Leave-One-Group-Out (LOGO) Cross-Cohort Validation\n"
            "- **Motivation:** Clinical machine learning models frequently degrade when deployed to unseen hospitals due to demographic, pre-test, and protocol shifts.\n"
            "- **Execution:** Four separate splits where three hospital centres serve as the training set, and the remaining centre acts as an unseen external test cohort.\n"
            "- **Findings:** Models experience significant generalisation drops on Switzerland (ROC AUC ~0.70–0.78), highlighting the vulnerability of standard classifiers to real-world hospital distribution shifts."
        )

    with t3:
        st.subheader("Explainability & Nonlinear Interactions: SHAP vs Permutation")
        st.markdown(
            "#### SHAP (SHapley Additive exPlanations)\n"
            "- **Game-Theoretic Attribution:** Computes exact Shapley values reflecting each feature's marginal contribution across all feature subsets.\n"
            "- **Continuous Interaction Surfaces:** Uncovers complex nonlinear risk dynamics (e.g., Age × Max Heart Rate, Resting Blood Pressure × Chest Pain Type).\n"
            "- **Neural Advantage:** Demonstrates how the Tabular MLP learns smooth, continuous interaction surfaces rather than rigid discrete step functions."
        )
        col1, col2 = st.columns(2)
        with col1:
            _img("results/phase2/main/figures/mlp_shap_beeswarm.png", "MLP Global SHAP Beeswarm")
        with col2:
            _img("results/phase2/main/figures/mlp_shap_bar_importance.png", "Mean |SHAP| Value per Predictor")

        st.markdown("#### Classical Permutation Feature Importance")
        st.markdown(
            "Measures the drop in validation ROC AUC when each feature column is randomly shuffled. "
            "Unlike SHAP, permutation importance measures global degradation but cannot uncover local individual contributions or multi-feature interactions."
        )
        _img("results/figures/feature_importance.png", "Phase 1 Permutation feature importance")

    with t4:
        st.subheader("Phase 1 Pipelines & Classical Model Specifications")
        st.markdown(
            "**Target.** `num = 0` -> 0, `num` in {1,2,3,4} -> 1 (164 negative, 139 positive).\n\n"
            "**Preprocessing (fitted on training folds only).** Logistic Regression, SVM, Random Forest and Gradient Boosting: median / most-frequent "
            "imputation, standardisation, one-hot nominal features (20 inputs). Bayesian network and Naive Bayes: train-fold tertile bins for continuous "
            "features, integer-coded states, missing or unseen values set to the training mode (13 inputs).\n\n"
            "**Naive Bayes.** Class -> every predictor; assumes predictors are independent given the class, which is violated here "
            "(for example oldpeak/slope, cp/exang), so its probabilities tend to be too extreme.\n\n"
            "**Logistic Regression.** A weighted sum of the inputs passed through the logistic (sigmoid) function; L2 penalty, strength tuned (C).\n\n"
            "**SVM.** RBF-kernel support vector machine (C and gamma tuned); Platt scaling turns its scores into probabilities.\n\n"
            "**Random Forest.** Many shallow decision trees on bootstrap samples, averaged (number of trees and depth tuned).\n\n"
            "**Gradient Boosting.** Small trees added one at a time, each correcting the previous ones (learning rate, number of trees, depth tuned)."
        )

    with t5:
        st.subheader("Domain-Informed Bayesian Network")
        st.markdown(
            "The structure is a **domain-informed assumption** fixed before any evaluation. It is not learned from data and is not evidence of causation; "
            "only the probability tables are estimated from the training fold."
        )
        _img("results/figures/bn_structure.png", "Assumed Bayesian-network structure")
        et = edge_table()[["parent", "child", "kind", "rationale"]]
        st.dataframe(et, hide_index=True)
        st.caption("domain = clinical reasoning accepted as an assumption; modelling = added to relax Naive Bayes independence; weak = plausible but weakly motivated.")

    with t6:
        st.subheader("Limitations and Research Ethics")
        st.markdown(
            "- **Multi-Cohort Gaps:** Although Phase 2 evaluates 920 patients across 4 centres, significant missingness in fluoroscopy (`ca`) and thallium scintigraphy (`thal`) in Zurich and Long Beach limits complete feature evaluation.\n"
            "- **Referral & Selection Bias:** Hospital cohorts represent high-prevalence referred populations (55.2% disease rate), not primary care general populations. Models cannot be used for first-contact triage.\n"
            "- **Binary Endpoints:** Grouping Duke severity grades 1–4 into a single binary target discards disease extent (single-vessel vs left-main triple-vessel disease).\n"
            "- **Demographic Disparities:** Male predominance across historical cohorts limits sex-disaggregated certainty; no formal algorithmic fairness audit has been validated.\n"
            "- **Non-Diagnostic Research Tool:** This software is strictly an academic benchmark and demonstration, NOT a medical device."
        )

    footer()
